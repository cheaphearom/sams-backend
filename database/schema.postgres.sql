-- Report views
CREATE VIEW v_class_attendance_summary AS
SELECT
  c.id AS class_id,
  c.name AS class_name,
  COUNT(DISTINCT ar.student_id) AS student_count,
  SUM(CASE WHEN ar.status = 'present' THEN 1 ELSE 0 END) AS present_count,
  SUM(CASE WHEN ar.status = 'absent' THEN 1 ELSE 0 END) AS absent_count,
  SUM(CASE WHEN ar.status = 'late' THEN 1 ELSE 0 END) AS late_count,
  COUNT(ar.id) AS total_records
FROM attendance_records ar
JOIN attendance_sessions asess ON ar.attendance_session_id = asess.id
JOIN schedules sch ON asess.schedule_id = sch.id
JOIN class_subjects cs ON sch.class_subject_id = cs.id
JOIN classes c ON cs.class_id = c.id
GROUP BY c.id, c.name;

CREATE VIEW v_monthly_attendance_summary AS
SELECT
  to_char(asess.session_date, 'YYYY-MM') AS ym,
  c.id AS class_id,
  c.name AS class_name,
  COUNT(DISTINCT ar.student_id) AS student_count,
  SUM(CASE WHEN ar.status = 'present' THEN 1 ELSE 0 END) AS present_count,
  SUM(CASE WHEN ar.status = 'absent' THEN 1 ELSE 0 END) AS absent_count,
  SUM(CASE WHEN ar.status = 'late' THEN 1 ELSE 0 END) AS late_count,
  COUNT(ar.id) AS total_records,
  ROUND(SUM(CASE WHEN ar.status = 'present' THEN 1 ELSE 0 END)::numeric / COUNT(ar.id) * 100, 2) AS present_percent
FROM attendance_records ar
JOIN attendance_sessions asess ON ar.attendance_session_id = asess.id
JOIN schedules sch ON asess.schedule_id = sch.id
JOIN class_subjects cs ON sch.class_subject_id = cs.id
JOIN classes c ON cs.class_id = c.id
GROUP BY ym, c.id, c.name;

CREATE VIEW v_student_attendance AS
SELECT
  ar.id AS attendance_record_id,
  asess.session_date,
  ar.student_id,
  s.first_name AS student_name,
  s.student_code,
  ar.status AS attendance_status,
  ar.remark,
  c.id AS class_id,
  c.name AS class_name,
  sub.id AS subject_id,
  sub.name AS subject_name,
  t.id AS teacher_id,
  t.first_name AS teacher_name
FROM attendance_records ar
JOIN attendance_sessions asess ON ar.attendance_session_id = asess.id
JOIN schedules sch ON asess.schedule_id = sch.id
JOIN class_subjects cs ON sch.class_subject_id = cs.id
JOIN classes c ON cs.class_id = c.id
JOIN subjects sub ON cs.subject_id = sub.id
LEFT JOIN teachers t ON cs.teacher_id = t.id
JOIN students s ON ar.student_id = s.id;

CREATE VIEW v_subject_attendance_summary AS
SELECT
  sub.id AS subject_id,
  sub.name AS subject_name,
  c.id AS class_id,
  c.name AS class_name,
  s.id AS student_id,
  s.first_name AS student_name,
  SUM(CASE WHEN ar.status = 'present' THEN 1 ELSE 0 END) AS present_count,
  SUM(CASE WHEN ar.status = 'absent' THEN 1 ELSE 0 END) AS absent_count,
  SUM(CASE WHEN ar.status = 'late' THEN 1 ELSE 0 END) AS late_count,
  COUNT(ar.id) AS total_records,
  ROUND(SUM(CASE WHEN ar.status = 'present' THEN 1 ELSE 0 END)::numeric / COUNT(ar.id) * 100, 2) AS present_percent
FROM attendance_records ar
JOIN attendance_sessions asess ON ar.attendance_session_id = asess.id
JOIN schedules sch ON asess.schedule_id = sch.id
JOIN class_subjects cs ON sch.class_subject_id = cs.id
JOIN subjects sub ON cs.subject_id = sub.id
JOIN classes c ON cs.class_id = c.id
JOIN students s ON ar.student_id = s.id
GROUP BY sub.id, c.id, s.id;

CREATE VIEW v_teacher_attendance AS
SELECT
  ta.id AS teacher_attendance_id,
  asess.session_date,
  t.id AS teacher_id,
  t.first_name AS teacher_name,
  c.id AS class_id,
  c.name AS class_name,
  sub.id AS subject_id,
  sub.name AS subject_name,
  ta.status AS attendance_status,
  ta.remark
