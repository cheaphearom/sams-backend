-- Replaces MySQL's "ON UPDATE CURRENT_TIMESTAMP"
CREATE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
    NEW.updated_at := CURRENT_TIMESTAMP;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- MySQL enums accepted any letter case and stored the lowercase value
CREATE FUNCTION lowercase_status() RETURNS trigger AS $$
BEGIN
  NEW.status := lower(NEW.status);
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  email VARCHAR(150) NOT NULL,
  avatar VARCHAR(255),
  first_name VARCHAR(100),
  last_name VARCHAR(100),
  image VARCHAR(255),
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL CHECK (role IN ('admin', 'teacher', 'student')),
  created_at TIMESTAMP(0),
  updated_at TIMESTAMP(0)
);
-- Emails stay unique regardless of letter case, as they were in MySQL
CREATE UNIQUE INDEX users_email_unique ON users (lower(email));

CREATE TABLE faculties (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
