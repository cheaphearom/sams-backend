// Uploaded files are stored in PostgreSQL instead of the local uploads/ folder.
// Vercel's file system is read-only (EROFS), so files written there fail;
// the database works the same locally and on Vercel.
// Files are still served at /uploads/<folder>/<filename> (see app.js), so the
// filenames saved in the other tables and the frontend URLs don't change.
const crypto = require('crypto');
const multer = require('multer');
const pool = require('../config/db');

const MAX_FILE_BYTES = 4 * 1024 * 1024; // 4 MB, Vercel rejects request bodies over 4.5 MB

let tableReady = null;
function ensureTable() {
  if (!tableReady) {
    tableReady = pool
      .query(
        `CREATE TABLE IF NOT EXISTS uploaded_files (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          path VARCHAR(255) NOT NULL UNIQUE,
          content_type VARCHAR(100) NOT NULL,
          data BYTEA NOT NULL,
          created_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
        )`
      )
      .catch((err) => {
        tableReady = null; // try again on the next upload
        throw err;
      });
  }
  return tableReady;
}

// Save (or replace) a file, path looks like "schools/1793608370774-ab12cd.png"
async function saveFile(path, buffer, contentType) {
  await ensureTable();
  await pool.query(
    `INSERT INTO uploaded_files (path, content_type, data) VALUES (?, ?, ?)
     ON CONFLICT (path) DO UPDATE
     SET content_type = EXCLUDED.content_type, data = EXCLUDED.data, created_at = CURRENT_TIMESTAMP`,
    [path, contentType, buffer]
  );
}

async function getFile(path) {
  await ensureTable();
  const [rows] = await pool.query(
    'SELECT content_type, data FROM uploaded_files WHERE path = ?',
    [path]
  );
  return rows[0] || null;
}

function newFilename(originalname) {
  const ext = (originalname.split('.').pop() || '').toLowerCase().replace(/[^a-z0-9]/g, '');
  const unique = `${Date.now()}-${crypto.randomBytes(3).toString('hex')}`;
  return ext ? `${unique}.${ext}` : unique;
}

// Drop-in replacement for multer(...).single(field): keeps the file in memory,
// saves it to the database and sets req.file.filename like disk storage did
function uploadImage(folder, field = 'image') {
  const parse = multer({
    storage: multer.memoryStorage(),
    limits: { fileSize: MAX_FILE_BYTES },
    fileFilter: (req, file, cb) => {
      if (file.mimetype.startsWith('image/')) return cb(null, true);
      const err = new Error('Only image files can be uploaded');
      err.status = 400;
      cb(err);
    }
  }).single(field);

  return (req, res, next) => {
    parse(req, res, async (err) => {
      if (err) {
        const message =
          err.code === 'LIMIT_FILE_SIZE'
            ? `Image is too large, the limit is ${MAX_FILE_BYTES / 1024 / 1024} MB`
            : err.message;
        return res.status(err.status || 400).json({ message });
      }
      if (!req.file) return next();

      try {
        const filename = newFilename(req.file.originalname);
        await saveFile(`${folder}/${filename}`, req.file.buffer, req.file.mimetype);
        req.file.filename = filename;
        next();
      } catch (saveErr) {
        next(saveErr);
      }
    });
  };
}

// Express handler for GET /uploads/:folder/:filename,
// falls through to the static uploads/ folder when the file isn't in the database
async function serveFile(req, res, next) {
  try {
    const file = await getFile(`${req.params.folder}/${req.params.filename}`);
    if (!file) return next();

    res.set('Content-Type', file.content_type);
    // Uploaded images get a new name every time, QR codes keep theirs and change
    res.set(
      'Cache-Control',
      req.params.folder === 'qrcodes' ? 'no-cache' : 'public, max-age=31536000, immutable'
    );
    res.send(file.data);
  } catch (err) {
    next(err);
  }
}

module.exports = { uploadImage, saveFile, getFile, serveFile };
